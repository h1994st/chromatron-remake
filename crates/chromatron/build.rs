//! Decodes each game's data from its original binary and writes it as Rust `static`s into
//! `OUT_DIR`, so the app embeds the data and never parses anything at runtime.

use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::ExitCode;
use std::{env, fs};

use spectrograph::{Game, GameData, decode, originals_dir};

/// The games this crate embeds, and the file each one's data goes to.
const EMBEDDED: [(Game, &str); 4] = [
    (Game::C1, "chromatron1_data.rs"),
    (Game::C2, "chromatron2_data.rs"),
    (Game::C3, "chromatron3_data.rs"),
    (Game::C4, "chromatron4_data.rs"),
];

fn main() -> ExitCode {
    println!("cargo::rerun-if-env-changed=CHROMATRON_ORIGINALS");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    for (game, file) in EMBEDDED {
        println!(
            "cargo::rerun-if-changed={}",
            game.binary_path(&originals_dir()).display()
        );
        let decoded = game
            .read_original()
            .and_then(|binary| decode(game, &binary).map_err(|e| e.to_string()));
        let data = match decoded {
            Ok(data) => data,
            Err(message) => {
                println!("cargo::error=cannot embed the game data: {message}");
                return ExitCode::FAILURE;
            }
        };
        let path = out_dir.join(file);
        if let Err(e) = fs::write(&path, game_data_source(&data)) {
            println!("cargo::error=cannot write {}: {e}", path.display());
            return ExitCode::FAILURE;
        }
    }
    ExitCode::SUCCESS
}

/// `pub static GAME: GameData = …;` reproducing `data` with borrowed slices and strings.
fn game_data_source(data: &GameData) -> String {
    let mut s = String::new();
    s.push_str("// Generated by build.rs from the original binary. Do not edit or commit.\n");
    s.push_str("pub static GAME: ::spectrograph::GameData = ::spectrograph::GameData {\n");
    let _ = writeln!(s, "    game: ::spectrograph::Game::{:?},", data.game);
    s.push_str("    levels: ::std::borrow::Cow::Borrowed(&[\n");
    for level in data.levels.iter() {
        let _ = write!(
            s,
            "        ::spectrograph::Level {{ game: ::spectrograph::Game::{:?}, id: {}, records: ::std::borrow::Cow::Borrowed(&[",
            level.game, level.id
        );
        for r in level.records.iter() {
            let _ = write!(
                s,
                "::spectrograph::Record {{ kind: {}, dir: {}, colour: {}, x: {}, y: {} }}, ",
                r.kind, r.dir, r.colour, r.x, r.y
            );
        }
        let _ = writeln!(
            s,
            "]), name: ::std::borrow::Cow::Borrowed({:?}), hint: ::std::borrow::Cow::Borrowed({:?}) }},",
            level.name.as_ref(),
            level.hint.as_ref()
        );
    }
    s.push_str("    ]),\n");
    let _ = writeln!(
        s,
        "    level_order: ::std::borrow::Cow::Borrowed(&{:?}),",
        data.level_order.as_ref()
    );
    s.push_str("    sprites: ::std::borrow::Cow::Borrowed(&[\n");
    for sprite in data.sprites.iter() {
        let _ = writeln!(s, "        {:?},", sprite.as_slice());
    }
    s.push_str("    ]),\n");
    let _ = writeln!(s, "    palette: {:?},", data.palette);
    let _ = writeln!(s, "    beam_colors: {:?},", data.beam_colors);
    s.push_str("    ui: ::spectrograph::UiText {\n");
    let ui = &data.ui;
    for (field, value) in [
        ("window_title", &ui.window_title),
        ("you_win", &ui.you_win),
        ("won", &ui.won),
        ("click_next", &ui.click_next),
        ("freeware", &ui.freeware),
        ("more_levels", &ui.more_levels),
        ("thank_you", &ui.thank_you),
        ("site_url", &ui.site_url),
    ] {
        let _ = writeln!(
            s,
            "        {field}: ::std::borrow::Cow::Borrowed({:?}),",
            value.as_ref()
        );
    }
    s.push_str("    },\n};\n");
    s
}
