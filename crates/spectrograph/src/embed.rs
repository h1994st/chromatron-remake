//! Rust source for a game's data as `static`s, so a build script can embed it and the binary
//! never parses an original at runtime. Used by the `chromatron` and `chromatron-web` build
//! scripts.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use crate::{Game, GameData, decode};

/// The file `embed_game` writes `game`'s data to; the crate includes it with
/// `include!(concat!(env!("OUT_DIR"), "/chromatron1_data.rs"))`.
pub fn data_file_name(game: Game) -> String {
    format!("chromatron{}_data.rs", game.number())
}

/// Decodes `game` from its original (in `originals_dir()`) and writes `game_data_source` of it to
/// `out_dir/data_file_name(game)`.
pub fn embed_game(game: Game, out_dir: &Path) -> Result<(), String> {
    let binary = game.read_original()?;
    let data = decode(game, &binary).map_err(|e| e.to_string())?;
    let path = out_dir.join(data_file_name(game));
    fs::write(&path, game_data_source(&data))
        .map_err(|e| format!("cannot write {}: {e}", path.display()))
}

/// `pub static GAME: GameData = …;` reproducing `data` with borrowed slices and strings.
pub fn game_data_source(data: &GameData) -> String {
    let mut s = String::new();
    s.push_str("// Generated by build.rs from the original binary. Do not edit or commit.\n");
    s.push_str("pub static GAME: ::spectrograph::GameData = ::spectrograph::GameData {\n");
    let _ = writeln!(s, "    game: ::spectrograph::Game::{:?},", data.game);
    s.push_str("    levels: ::std::borrow::Cow::Borrowed(&[\n");
    for level in data.levels.iter() {
        let _ = write!(
            s,
            "        ::spectrograph::Level {{ game: ::spectrograph::Game::{:?}, id: {}, records: ::std::borrow::Cow::Borrowed(&[",
            level.game, level.id
        );
        for r in level.records.iter() {
            let _ = write!(
                s,
                "::spectrograph::Record {{ kind: {}, dir: {}, colour: {}, x: {}, y: {} }}, ",
                r.kind, r.dir, r.colour, r.x, r.y
            );
        }
        let _ = writeln!(
            s,
            "]), name: ::std::borrow::Cow::Borrowed({:?}), hint: ::std::borrow::Cow::Borrowed({:?}) }},",
            level.name.as_ref(),
            level.hint.as_ref()
        );
    }
    s.push_str("    ]),\n");
    let _ = writeln!(
        s,
        "    level_order: ::std::borrow::Cow::Borrowed(&{:?}),",
        data.level_order.as_ref()
    );
    s.push_str("    sprites: ::std::borrow::Cow::Borrowed(&[\n");
    for sprite in data.sprites.iter() {
        let _ = writeln!(s, "        {:?},", sprite.as_slice());
    }
    s.push_str("    ]),\n");
    let _ = writeln!(s, "    palette: {:?},", data.palette);
    let _ = writeln!(s, "    beam_colors: {:?},", data.beam_colors);
    s.push_str("    ui: ::spectrograph::UiText {\n");
    let ui = &data.ui;
    for (field, value) in [
        ("window_title", &ui.window_title),
        ("you_win", &ui.you_win),
        ("won", &ui.won),
        ("click_next", &ui.click_next),
        ("freeware", &ui.freeware),
        ("more_levels", &ui.more_levels),
        ("thank_you", &ui.thank_you),
        ("site_url", &ui.site_url),
    ] {
        let _ = writeln!(
            s,
            "        {field}: ::std::borrow::Cow::Borrowed({:?}),",
            value.as_ref()
        );
    }
    s.push_str("    },\n};\n");
    s
}

#[cfg(test)]
mod tests {
    use std::borrow::Cow;

    use super::*;
    use crate::{Level, Record, SPRITE_LEN, UiText};

    fn tiny() -> GameData {
        GameData {
            game: Game::C2,
            levels: Cow::Owned(vec![Level {
                game: Game::C2,
                id: 7,
                records: Cow::Owned(vec![Record {
                    kind: 1,
                    dir: 2,
                    colour: 3,
                    x: 4,
                    y: 5,
                }]),
                name: Cow::Borrowed("Seven"),
                hint: Cow::Borrowed("say \"hi\""),
            }]),
            level_order: Cow::Owned(vec![7, 7]),
            sprites: Cow::Owned(vec![[9; SPRITE_LEN]]),
            palette: [0x123456; 256],
            beam_colors: [0xabcdef; 8],
            ui: UiText {
                window_title: Cow::Borrowed("Chromatron 2 (v1.4)"),
                you_win: Cow::Borrowed("You win!"),
                won: Cow::Borrowed(""),
                click_next: Cow::Borrowed(""),
                freeware: Cow::Borrowed(""),
                more_levels: Cow::Borrowed(""),
                thank_you: Cow::Borrowed(""),
                site_url: Cow::Borrowed(""),
            },
        }
    }

    #[test]
    fn the_source_is_one_static_of_borrowed_data() {
        let source = game_data_source(&tiny());
        assert!(source.starts_with(
            "// Generated by build.rs from the original binary. Do not edit or commit.\n\
             pub static GAME: ::spectrograph::GameData = ::spectrograph::GameData {\n    \
             game: ::spectrograph::Game::C2,\n"
        ));
        assert!(source.contains(
            "        ::spectrograph::Level { game: ::spectrograph::Game::C2, id: 7, records: \
             ::std::borrow::Cow::Borrowed(&[::spectrograph::Record { kind: 1, dir: 2, colour: 3, \
             x: 4, y: 5 }, ]), name: ::std::borrow::Cow::Borrowed(\"Seven\"), hint: \
             ::std::borrow::Cow::Borrowed(\"say \\\"hi\\\"\") },\n"
        ));
        assert!(source.contains("    level_order: ::std::borrow::Cow::Borrowed(&[7, 7]),\n"));
        assert!(source.contains(
            "        window_title: ::std::borrow::Cow::Borrowed(\"Chromatron 2 (v1.4)\"),\n"
        ));
        assert!(source.contains("        you_win: ::std::borrow::Cow::Borrowed(\"You win!\"),\n"));
        assert!(source.ends_with("    },\n};\n"));
    }

    #[test]
    fn each_game_has_its_own_file() {
        let names: Vec<String> = Game::ALL.into_iter().map(data_file_name).collect();
        assert_eq!(
            names,
            [
                "chromatron1_data.rs",
                "chromatron2_data.rs",
                "chromatron3_data.rs",
                "chromatron4_data.rs"
            ]
        );
    }
}
